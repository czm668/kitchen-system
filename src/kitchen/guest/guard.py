# -*- coding: utf-8 -*-
"""对客回复的禁语自检：模型说错一句话，比答得慢严重得多。

## 为什么要有这一层

`handler.compose_reply` 只校验「回复里有没有具体事实」（`reply_has_concrete_info`），
管不了**说了不该说的**：

* 「马上就好」——系统里没有任何出餐倒计时数据，这是凭空的承诺；
* 「已经给您退了」——演示环境 `settled` 恒 0，这句话与代码事实直接冲突；
* 「热销第一」——系统不采集销量，主推位是运营指定的；
* 「绝对不含过敏原」——配方只记主料，没做过敏原检测。

这些话术在离线规则层不会出现（模板是干净的），但**在线模型会写**：它看过太多
餐厅客服语料，"马上就好"几乎是它的默认口头禅。所以约束必须落在出口，而不是
指望提示词。

## 处理策略：改写而不是拦截

命中即替换成同义但**有事实依据**的说法，回复照常发出——顾客要的是答案，
不是一句「系统繁忙」。同时把命中项返回给调用方，落进 `handling["guard"]`，
质检按它统计「模型违规率」，这也是唯一能证明这层护栏有效的证据。

## 边界

* 只处理**对客文案**，不改工单字段、不改 state；
* 替换是**保守**的：宁可话说得笨一点，也不留任何越权承诺；
* 词表覆盖的是已知高风险说法，不追求 NLP 级语义识别（那属于模型侧的事）。
"""
from __future__ import annotations

from typing import Any

__all__ = ["BANNED", "scan", "scrub", "UNSAFE_PROMISE"]

#: 越权承诺 → 有事实依据的替代说法。
#: 顺序有意义：长词在前，避免「已退款」被「退款」先切一半。
BANNED: tuple[tuple[str, str], ...] = (
    # 1) 资金类：演示环境没有支付链路，任何「已退/已赔」都是假话
    ("已经给您退了", "补偿还没批下来，需要管理人员终审后生成凭证"),
    ("已经退款", "补偿还没批下来，需要管理人员终审后生成凭证"),
    ("已退款", "补偿还没批下来，需要管理人员终审后生成凭证"),
    ("钱已退回", "补偿还没批下来，需要管理人员终审后生成凭证"),
    ("原路退回", "补偿还没批下来，需要管理人员终审后生成凭证"),
    ("马上给您退", "退款需要管理人员核实后审批"),
    ("肯定能批", "需要管理人员核实订单与证据后答复"),
    ("一定能批", "需要管理人员核实订单与证据后答复"),
    # 2) 时间类：没有出餐倒计时，不许报点。
    #    替代句刻意不含主语，因为它可能被拼在任何句子后面
    #    （「您的菜马上就到」→「您的菜正在出餐，超时会自动升级」）。
    ("马上就好", "正在出餐，超时会自动升级"),
    ("马上上来", "正在出餐，超时会自动升级"),
    ("马上就到", "正在出餐，超时会自动升级"),
    ("马上到", "正在出餐，超时会自动升级"),
    ("三分钟就好", "正在出餐，超时会自动升级"),
    ("五分钟就好", "正在出餐，超时会自动升级"),
    # 3) 销量类：系统不采集销量
    ("销量第一", "主推位是门店运营按菜品定的，不按销量"),
    ("热销第一", "主推位是门店运营按菜品定的，不按销量"),
    ("卖得最好", "主推位是门店运营按菜品定的，不按销量"),
    ("最受欢迎", "主推位是门店运营按菜品定的，不按销量"),
    # 4) 食安类：只记主料，没做过敏原检测，不能打包票
    ("绝对不含", "配料以配方为准，我帮您跟厨房核实"),
    ("绝对没问题", "我帮您跟厨房核实"),
    ("百分百安全", "我帮您跟厨房核实"),
    ("百分之百", "我帮您跟厨房核实"),
    ("保证不会", "我帮您跟厨房核实"),
    # 5) 推责类：把顾客推到对立面，是最容易升级成舆情的一句
    ("不是我们的问题", "我先帮您核实，不急着下结论"),
    ("我们员工不会这样", "我调当班的记录核实一下"),
    ("图片仅供参考", "实际分量我帮您跟厨房核对"),
)

#: 只出现在「越权承诺」语境的关键词，供质检归类（不参与替换）。
UNSAFE_PROMISE = ("已退", "已赔", "保证", "绝对", "百分之百", "肯定能")


def scan(text: Any) -> list[dict[str, str]]:
    """扫出命中的禁语，不改原文。质检与单测用它。"""
    raw = str(text or "")
    return [{"term": term, "replacement": repl}
            for term, repl in BANNED if term in raw]


def scrub(text: Any) -> tuple[str, list[dict[str, str]]]:
    """替换禁语，返回 `(改写后文本, 命中清单)`。

    命中清单为空是常态——它只该在**在线模型**回复里出现。
    """
    raw = str(text or "")
    hits: list[dict[str, str]] = []
    for term, repl in BANNED:
        if term in raw:
            hits.append({"term": term, "replacement": repl})
            raw = raw.replace(term, repl)
    return raw, hits
